Placetovisit = {
    "France",
    "Italy",
    "Japan",
    "Brazil",
    "Australia"}

print("Here is the original set of places to visit:")
print(Placetovisit)

# Using sorted() to display the set in alphabetical order without modifying the original set
print("\nHere is the set in alphabetical order:")
print(sorted(Placetovisit))

# Showing that the original set is unchanged
print("\nHere is the original set again:")
print(Placetovisit)


 